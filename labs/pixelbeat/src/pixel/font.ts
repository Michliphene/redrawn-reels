export type Plot = (x: number, y: number) => void;

/** Largeur en pixels (avant échelle). */
export const textWidth = (text: string) => {
  let w = 0;
  let sup = false;
  for (const ch of text.toUpperCase()) {
    if (ch === '^') { sup = true; continue; }
    if (ch === ' ') sup = false;
    w += sup ? 4 : 6;
  }
  return Math.max(0, w - 1);
};

/** Dessine le texte ; chaque pixel de glyphe devient un bloc scale×scale. */
export const drawText = (plot: Plot, text: string, x0: number, y0: number, scale = 1) => {
  let x = x0;
  let sup = false;
  for (const ch of text.toUpperCase()) {
    if (ch === '^') { sup = true; continue; }
    if (ch === ' ') sup = false;
    const g = sup ? MINI[ch] : G[ch] ?? G['?'];
    if (!g) { x += (sup ? 4 : 6) * scale; continue; }
    const yOff = sup ? -2 : 0;
    g.forEach((row, ry) => {
      for (let rx = 0; rx < row.length; rx++) {
        if (row[rx] !== '1') continue;
        for (let sy = 0; sy < scale; sy++)
          for (let sx = 0; sx < scale; sx++) plot(x + rx * scale + sx, y0 + (ry + yOff) * scale + sy);
      }
    });
    x += (sup ? 4 : 6) * scale;
  }
};
