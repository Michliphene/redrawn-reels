"""Instrument Serif Italic glyphs -> SVG paths for the 3D bottle label (raea textures can't load web fonts).

Writes src/glyphs.gen.ts: { unitsPerEm, ascender, glyphs: { char: { d, adv } } } for the characters the label uses.
Run once (or after changing CHARS): python raea/sillage-kit/tools/glyphs.py
Needs fontTools + brotli (pip install fonttools brotli).
"""
import json
import pathlib

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[3]
FONT = ROOT / "public/fonts/InstrumentSerif-Italic-latin.woff2"
OUT = pathlib.Path(__file__).resolve().parents[1] / "src/glyphs.gen.ts"
CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789°·.-– "

font = TTFont(str(FONT))
gs = font.getGlyphSet()
cmap = font.getBestCmap()
glyphs = {}
for ch in CHARS:
    name = cmap.get(ord(ch))
    if name is None:
        continue
    pen = SVGPathPen(gs)
    gs[name].draw(pen)
    glyphs[ch] = {"d": pen.getCommands(), "adv": gs[name].width}

data = {"unitsPerEm": font["head"].unitsPerEm, "ascender": font["hhea"].ascent, "glyphs": glyphs}
OUT.write_text(
    "// generated by tools/glyphs.py from public/fonts/InstrumentSerif-Italic-latin.woff2 (OFL) — do not edit\n"
    f"export const GLYPHS = {json.dumps(data, ensure_ascii=False)} as const;\n",
    encoding="utf-8",
)
print(f"{len(glyphs)} glyphs -> {OUT}")
